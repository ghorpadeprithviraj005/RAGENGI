"""
Unit tests for app/ingestion/pdf_extractor.py.

These tests generate real (small, in-memory-built) PDF files with PyMuPDF
itself rather than relying on checked-in binary fixture files, so the test
suite has no external file dependencies and is fully reproducible offline.
"""

import fitz
import pytest

from app.ingestion.pdf_extractor import (
    PDFCorruptedError,
    PDFEmptyError,
    PDFExtractor,
    PDFNotFoundError,
)


@pytest.fixture
def extractor() -> PDFExtractor:
    return PDFExtractor()


def _make_pdf(tmp_path, pages_text, filename: str = "sample.pdf"):
    """Create a real PDF on disk with one page per string in `pages_text`."""
    document = fitz.open()
    for text in pages_text:
        page = document.new_page()
        if text:
            page.insert_text((72, 72), text)
    path = tmp_path / filename
    document.save(path)
    document.close()
    return path


def _make_zero_page_pdf(tmp_path, filename: str = "empty.pdf"):
    """
    Hand-construct a minimal, structurally valid PDF whose Pages tree has zero
    Kids (i.e. a genuinely valid PDF file with no pages).

    PyMuPDF's own `Document.save()` refuses to write a zero-page document
    (`ValueError: cannot save with zero pages`), so this edge case -- a file
    that opens without error but has no pages -- can only be produced by
    writing the PDF structure directly. This mirrors how such a file could
    arrive in practice (e.g. generated by a different, non-PyMuPDF tool).
    """
    pdf_bytes = (
        b"%PDF-1.4\n"
        b"1 0 obj\n<< /Type /Catalog /Pages 2 0 R >>\nendobj\n"
        b"2 0 obj\n<< /Type /Pages /Kids [] /Count 0 >>\nendobj\n"
        b"trailer\n<< /Size 3 /Root 1 0 R >>\n%%EOF\n"
    )
    path = tmp_path / filename
    path.write_bytes(pdf_bytes)
    return path


def test_extract_valid_pdf_returns_text_per_page(tmp_path, extractor):
    pdf_path = _make_pdf(tmp_path, ["Hello page one", "Hello page two"])

    result = extractor.extract(str(pdf_path))

    assert result.page_count == 2
    assert len(result.pages) == 2
    assert result.pages[0].page_number == 1
    assert result.pages[1].page_number == 2
    assert "Hello page one" in result.pages[0].text
    assert "Hello page two" in result.pages[1].text


def test_extract_flags_pages_with_no_native_text(tmp_path, extractor):
    # First page intentionally blank (simulates a scanned page with no text layer).
    pdf_path = _make_pdf(tmp_path, ["", "Some real text"])

    result = extractor.extract(str(pdf_path))

    assert result.pages[0].has_native_text is False
    assert result.pages[0].text == ""
    assert result.pages[1].has_native_text is True


def test_extract_missing_file_raises_not_found(extractor):
    with pytest.raises(PDFNotFoundError):
        extractor.extract("/nonexistent/path/does_not_exist.pdf")


def test_extract_directory_path_raises_not_found(tmp_path, extractor):
    with pytest.raises(PDFNotFoundError):
        extractor.extract(str(tmp_path))  # tmp_path is a directory, not a file


def test_extract_corrupted_pdf_raises_corrupted_error(tmp_path, extractor):
    bad_path = tmp_path / "corrupted.pdf"
    bad_path.write_bytes(b"this is not a real pdf file, just plain bytes")

    with pytest.raises(PDFCorruptedError):
        extractor.extract(str(bad_path))


def test_extract_non_pdf_extension_raises_corrupted_error(tmp_path, extractor):
    txt_path = tmp_path / "not_a_pdf.txt"
    txt_path.write_text("hello world")

    with pytest.raises(PDFCorruptedError):
        extractor.extract(str(txt_path))


def test_extract_empty_pdf_raises_empty_error(tmp_path, extractor):
    empty_path = _make_zero_page_pdf(tmp_path)

    with pytest.raises(PDFEmptyError):
        extractor.extract(str(empty_path))


def test_extract_result_preserves_page_order(tmp_path, extractor):
    pages_text = [f"Page number {i}" for i in range(1, 6)]
    pdf_path = _make_pdf(tmp_path, pages_text)

    result = extractor.extract(str(pdf_path))

    page_numbers = [p.page_number for p in result.pages]
    assert page_numbers == [1, 2, 3, 4, 5]
    for i, page in enumerate(result.pages, start=1):
        assert f"Page number {i}" in page.text
