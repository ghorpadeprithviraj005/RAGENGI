"""
Module 12: Engineering Answer Formatter

Structures the LLM output combined with EngineeringAnnotations from retrieved
chunks into a rich, categorized engineering response:
  - Technical Summary
  - Formula Section
  - Standard References
  - Unit Values
  - Figure/Table Citations
"""

import logging
from dataclasses import dataclass, field
from typing import List, Optional

from app.intelligence.analyzer import EngineeringAnnotation
from app.intelligence.detectors import EngineeringDomain

logger = logging.getLogger(__name__)


@dataclass
class EngineeringAnswer:
    """Fully structured engineering response payload."""
    raw_answer: str
    domain: EngineeringDomain
    technical_summary: str
    formulas: List[str] = field(default_factory=list)
    standards: List[str] = field(default_factory=list)
    units: List[str] = field(default_factory=list)
    figure_references: List[str] = field(default_factory=list)
    citations: List[dict] = field(default_factory=list)

    def to_formatted_text(self) -> str:
        """Render the structured answer as a printable text block."""
        sections = [
            f"[Domain: {self.domain.value}]\n",
            "── Technical Summary ──",
            self.technical_summary,
        ]
        if self.formulas:
            sections += ["\n── Formulas Detected ──"] + [f"  • {f}" for f in self.formulas]
        if self.standards:
            sections += ["\n── Standards Referenced ──"] + [f"  • {s}" for s in self.standards]
        if self.units:
            sections += ["\n── Engineering Units ──"] + [f"  • {u}" for u in self.units]
        if self.figure_references:
            sections += ["\n── Figures / Tables ──"] + [f"  • {r}" for r in self.figure_references]
        if self.citations:
            sections += ["\n── Citations ──"]
            for c in self.citations:
                sections.append(
                    f"  • {c.get('document_name', 'Unknown')} — Page {c.get('page_number')}, Chunk {c.get('chunk_id')}"
                )
        return "\n".join(sections)


class EngineeringFormatter:
    """
    Intercepts the raw LLM answer and retrieved chunk annotations to build
    a fully structured EngineeringAnswer. Fully offline.
    """

    def format_answer(
        self,
        raw_answer: str,
        annotations: List[EngineeringAnnotation],
        citations: Optional[List[dict]] = None,
    ) -> EngineeringAnswer:
        """
        Build a structured EngineeringAnswer from raw LLM output and chunk annotations.

        Args:
            raw_answer: The raw text generated by the LLM.
            annotations: List of EngineeringAnnotation objects from retrieved chunks.
            citations: List of citation dicts (chunk_id, page_number, document_name).

        Returns:
            A fully structured EngineeringAnswer instance.
        """
        if not annotations:
            logger.warning("No annotations provided to formatter. Returning minimal answer.")
            return EngineeringAnswer(
                raw_answer=raw_answer,
                domain=EngineeringDomain.GENERAL,
                technical_summary=raw_answer,
                citations=citations or [],
            )

        try:
            # Determine dominant domain by majority vote
            domain_votes: dict[EngineeringDomain, int] = {}
            for ann in annotations:
                domain_votes[ann.domain] = domain_votes.get(ann.domain, 0) + 1
            dominant_domain = max(domain_votes, key=lambda d: domain_votes[d])

            # Aggregate formulas (deduplicate by raw text)
            seen_formulas: set[str] = set()
            formulas: List[str] = []
            for ann in annotations:
                for f in ann.formulas:
                    if f.raw not in seen_formulas:
                        seen_formulas.add(f.raw)
                        formulas.append(f.raw)

            # Aggregate standards (deduplicated)
            seen_standards: set[str] = set()
            standards: List[str] = []
            for ann in annotations:
                for s in ann.standards:
                    if s.code not in seen_standards:
                        seen_standards.add(s.code)
                        standards.append(f"{s.standard_type}: {s.code}")

            # Aggregate units (unique values)
            seen_units: set[str] = set()
            units: List[str] = []
            for ann in annotations:
                for u in ann.units:
                    label = f"{u.value} {u.unit}"
                    if label not in seen_units:
                        seen_units.add(label)
                        units.append(label)

            # Aggregate figure / table references
            seen_refs: set[str] = set()
            refs: List[str] = []
            for ann in annotations:
                for r in ann.references:
                    label = f"{r.ref_type.capitalize()} {r.number}"
                    if label not in seen_refs:
                        seen_refs.add(label)
                        page_str = f" (Page {r.page_hint})" if r.page_hint else ""
                        refs.append(label + page_str)

            answer = EngineeringAnswer(
                raw_answer=raw_answer,
                domain=dominant_domain,
                technical_summary=raw_answer,
                formulas=formulas,
                standards=standards,
                units=units,
                figure_references=refs,
                citations=citations or [],
            )

            logger.info(
                f"Formatted engineering answer | Domain: {dominant_domain.value} | "
                f"Formulas: {len(formulas)} | Standards: {len(standards)}"
            )
            return answer

        except Exception as e:
            logger.error(f"EngineeringFormatter failed: {e}")
            raise
